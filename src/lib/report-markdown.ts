import type { AnalyticsReport } from "@/module/report/actions";

/** Serialize an analytics report to a portable Markdown document. */
export function buildReportMarkdown(report: AnalyticsReport, scopeLabel: string): string {
  const t = report.totals;
  const lines: string[] = [];

  lines.push(`# CodeTurtle - Review Report`);
  lines.push("");
  lines.push(`**Scope:** ${scopeLabel}`);
  lines.push(`**Generated:** ${new Date().toISOString().replace("T", " ").slice(0, 16)} UTC`);
  lines.push(`**Window:** last 6 months`);
  lines.push("");
  lines.push(`## Summary`);
  lines.push("");
  lines.push(`| Metric | Value |`);
  lines.push(`| --- | --- |`);
  lines.push(`| Reviews | ${t.reviews} |`);
  lines.push(`| Avg score | ${t.avgScore !== null ? `${t.avgScore}/10` : "-"} |`);
  lines.push(`| Issues found | ${t.totalIssues} |`);
  lines.push(`| Suggestions | ${t.totalSuggestions} |`);
  lines.push(`| Positives | ${t.totalPositives} |`);
  lines.push(`| Completion rate | ${t.completionRate}% |`);
  lines.push("");

  if (report.perRepo.length > 0) {
    lines.push(`## Per repository`);
    lines.push("");
    lines.push(`| Repository | Reviews | Avg score | Issues | Suggestions | Completion |`);
    lines.push(`| --- | --- | --- | --- | --- | --- |`);
    for (const r of report.perRepo) {
      lines.push(
        `| ${r.name} | ${r.reviews} | ${r.avgScore !== null ? `${r.avgScore}/10` : "-"} | ${r.issues} | ${r.suggestions} | ${r.completionRate}% |`,
      );
    }
    lines.push("");
  }

  if (report.severity.length > 0) {
    lines.push(`## Severity breakdown`);
    lines.push("");
    for (const s of report.severity) {
      lines.push(`- **${s.name}:** ${s.value}`);
    }
    lines.push("");
  }

  lines.push(`## Issue volume by week`);
  lines.push("");
  lines.push(`| Week | Critical | Warning | Info |`);
  lines.push(`| --- | --- | --- | --- |`);
  for (const w of report.issueVolume) {
    if (w.critical + w.warning + w.info === 0) continue;
    lines.push(`| ${w.label} | ${w.critical} | ${w.warning} | ${w.info} |`);
  }
  lines.push("");

  if (report.recentReviews.length > 0) {
    lines.push(`## Recent reviews`);
    lines.push("");
    for (const r of report.recentReviews.slice(0, 20)) {
      lines.push(
        `- [${r.repo}#${r.prNumber}](${r.prUrl ?? ""}) - ${r.prTitle ?? "(untitled)"} - score ${r.score ?? "-"}/10, ${r.issues} issue(s), ${r.suggestions} suggestion(s) - ${r.status}`,
      );
    }
    lines.push("");
  }

  lines.push(`---`);
  lines.push(`Generated by CodeTurtle`);

  return lines.join("\n");
}
